import assert from 'node:assert/strict';
import fs from 'node:fs';

const read=path=>fs.readFileSync(path,'utf8');
const app=read('web/app.js');
const shell=read('web/index.html');
const entry=read('web/app-v32-entry.js');
const runtime=read('web/app-runtime-v57.js');
const mobile=read('web/app-r56-mobile.js');
const master=read('web/app-master-v18.js');
const files=read('web/app-file-actions.js');
const orders=read('web/app-v32-orders.js');
const catalog=read('web/app-v32-catalog.js');
const sw=read('web/sw.js');

assert.equal((app.match(/window\.fetch\s*=/g)||[]).length,0,'app.js must not wrap global fetch');
assert.ok(!app.includes('initializeMasterOrderingV42'),'retired v42 ordering bootstrap must not initialize');
assert.ok(!shell.includes('app-r52-stability.js'),'retired R52 stability script must not load');
assert.ok(!shell.includes('app-r54-consolidation.js'),'retired R54 facade must not load');
assert.ok(shell.includes('app-r56-mobile.js'),'canonical mobile layer must load directly');
assert.ok(entry.includes('initializeRuntimeV57'),'professional entry must initialize canonical runtime');
assert.ok(!entry.includes('initializeExperienceV43'),'v43 experience layer must not initialize');
assert.ok(!entry.includes('initializeOperationalUpgradeV40'),'v40 DOM enhancer must not initialize');
assert.ok(!entry.includes('initializeMasterOrderingV42'),'v42 ordering layer must not initialize');
assert.ok(!fs.existsSync('web/app-v43-experience.js'),'v43 experience file must be removed');
assert.ok(!fs.existsSync('web/app-v42-master-ordering.js'),'v42 ordering facade must be removed');
assert.ok(runtime.includes("registerRouteRenderer('dashboard'"),'canonical runtime must own dashboard route');
assert.ok(runtime.includes("registerRouteRenderer('operations'"),'canonical runtime must own operations route');
assert.ok(master.includes('v18-master-nav{display:none!important}'),'legacy custom keyboard must remain disabled');
assert.ok(!master.includes("addEventListener('focusin'"),'master list must not steal native focus');
assert.ok(!master.includes("addEventListener('keydown'"),'master list must not hijack Enter');
assert.ok(!files.includes('IntersectionObserver'),'sharing must not generate PDFs from viewport observation');
assert.ok(!files.includes('MutationObserver'),'sharing must not scan the whole DOM');
assert.ok(orders.includes("order.status==='draft'"),'Por emitir must be sourced from drafts');
assert.ok(orders.includes("order.status!=='draft'&&order.status!=='cancelled'"),'History must exclude drafts and cancelled orders');
assert.ok(orders.includes('data-v57-order-actions'),'order actions must be a native select in canonical renderer');
assert.ok(!orders.includes('data-v43-order-menu'),'history must not depend on v43 menu patches');
assert.equal((catalog.match(/data-v32-photo=/g)||[]).length,1,'product card must expose one photo action');
assert.ok((mobile.match(/MutationObserver/g)||[]).length<=1,'mobile runtime may observe only the modal, not the whole document');
assert.ok(mobile.includes("observe(body,{subtree:true,childList:true})"),'mobile observer must be scoped to modal body');
assert.ok(sw.includes('nuvasto-v57-canonical-runtime'),'service worker release must be canonical v57');
console.log('canonical runtime regression gate: OK');
