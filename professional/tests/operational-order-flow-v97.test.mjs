import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {canTransition} from '../worker/src/core.js';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const server=read('../worker/src/worker-core.js'),receiving=read('../worker/src/api/reception-v13.js');
const detail=read('../web/app-order-detail-v30.js'),orders=read('../web/app-orders.js');
const invoice=read('../web/app-invoice-v30.js'),multi=read('../web/app-multi-invoice.js');
const master=read('../web/app-master-order.js');
assert.match(master,/openOrderDetail\(order\.id\)/,'canonical master editor returns to same draft');
assert.match(server,/const invoiceCount=Number\(invoices\?\.total\|\|0\)/);
assert.doesNotMatch(server,/if\(!Number\(invoices\?\.total\)\)throw/);
assert.match(server,/invoicePending:invoiceCount===0/);
assert.match(server,/status='completed'/);
assert.match(server,/transitionUrl\.pathname=.*transition/);
assert.match(receiving,/if\(order\.status==='draft'\)throw/);
assert.match(receiving,/if\(\['received','reconciled','closed','cancelled'\]\.includes\(order\.status\)\)throw/);
assert.ok(canTransition('partially_received','closed')&&canTransition('received','closed')&&canTransition('reconciled','closed'));
assert.ok(!canTransition('requested','closed')&&!canTransition('draft','closed'));
assert.match(detail,/Factura pendiente · no bloquea el cierre/);
assert.match(detail,/Puedes adjuntar la factura posteriormente desde Historial/);
assert.doesNotMatch(detail,/if\(!invoiceCount\)\{[\s\S]{0,300}openInvoiceAnalysisV30/);
assert.match(detail,/invoices\.length===0\)actions\.push/);
assert.doesNotMatch(detail,/await navigate\('dashboard'\)/);
assert.doesNotMatch(detail,/await navigate\('history'\)/);
assert.match(orders,/Control opcional · \$\{label\}/);
assert.match(orders,/if\(to==='closed'\)return openOrderDetail\(order\.id\)/);
assert.match(orders,/Adjuntar factura pendiente/);
assert.match(invoice,/if\(orderId\)await \(await import\('\.\/app-order-detail-v30\.js'\)\)\.openOrderDetail\(orderId\)/);
assert.match(multi,/if\(returnOrderId\)await \(await import\('\.\/app-order-detail-v30\.js'\)\)\.openOrderDetail\(returnOrderId\)/);
console.log('operational order flow v97: OK · no mandatory invoice and no navigation away');