import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>fs.readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const root=path=>fs.readFileSync(new URL(`../../${path}`,import.meta.url),'utf8');
const release=JSON.parse(read('release.json'));
const app=read('web/app.js');
const clientRelease=read('web/app-release.js');
const guard=read('web/app-release-guard.js');
const auth=read('web/app-auth-experience.js');
const bootstrap=read('web/app-bootstrap.js');
const sw=read('web/sw.js');
const swRelease=read('web/sw-release.js');
const invoice=read('worker/src/invoice-pricing-matrix.js');
const normalizer=read('worker/src/invoice-normalizer.js');
const passkeys=read('worker/src/api/passkeys.js');
const router=read('worker/src/router.js');
const payments=read('web/app-payment-workflow.js');
const workerRelease=root('worker/src/release.js');
const workerCombined=root('worker/src/combined.js');

assert.ok(clientRelease.includes(`CLIENT_RELEASE='${release.release}'`),'generated client release must match release.json');
assert.ok(workerRelease.includes(`PLATFORM_RELEASE='${release.release}'`),'generated platform release must match release.json');
assert.ok(swRelease.includes(`NUVASTO_RELEASE='${release.release}'`),'generated service-worker release must match release.json');
assert.ok(swRelease.includes(`NUVASTO_CACHE='${release.cache}'`),'service-worker cache must come from release.json');
assert.match(workerCombined,/from '\.\/release\.js'/,'platform release handshake must consume generated state');
assert.doesNotMatch(workerCombined,/const PLATFORM_RELEASE='[^']+'/,'platform worker must not duplicate the release literal');
assert.match(guard,/registration\.update\(\)/,'release mismatch must explicitly check for a new service worker');
assert.match(guard,/controllerchange/,'client must wait for new service-worker control before reloading when possible');
assert.match(guard,/purgeStaleRuntime/,'persistent mismatches must purge stale worker/cache state');
assert.match(app,/app-session-bootstrap\.js/,'session bootstrap must remain the first release gate');
assert.match(bootstrap,/app-navigation\.js/,'bootstrap must use current canonical navigation');
assert.doesNotMatch(bootstrap,/app-navigation-v14\.js|app-sso-v20\.js/,'retired navigation and SSO implementations must stay inactive');

assert.match(auth,/isUserVerifyingPlatformAuthenticatorAvailable/,'platform biometric availability detection is required');
assert.match(auth,/biometricIcon\(\)/,'biometric login must be icon based');
assert.match(auth,/navigator\.credentials\.get/,'passkey login is required');
assert.match(auth,/navigator\.credentials\.create/,'passkey enrollment is required');
assert.doesNotMatch(auth,/location\.reload\s*\(/,'biometric login must not reload the PWA');
assert.match(passkeys,/passkey_credentials/,'passkey persistence must remain active');
assert.match(passkeys,/passkey_user_verification_required/,'passkeys must require user verification');
assert.match(router,/passkeyAuthV72:true/,'passkey capability flag must remain exposed');
assert.match(router,/adaptiveInvoicePriceMatrixV78:true/,'adaptive invoice matrix capability must remain exposed');
assert.match(router,/sessionIdleExpiryV87:true/,'idle session expiry must remain exposed');
assert.match(invoice,/printed-final-unit-column/,'supplier printed final unit price remains highest-confidence path');
assert.match(invoice,/printed-line-sum-matrix/,'printed invoice sum inference must remain active');
assert.match(invoice,/invoice-line-component-matrix/,'component matrix fallback must remain active');
assert.match(normalizer,/reconcileInvoicePricing/,'invoice normalization must use canonical pricing reconciliation');

assert.match(sw,/importScripts\('\.\/sw-release\.js'\)/,'current service worker must load generated release state');
assert.match(sw,/Promise\.all\(PRECACHE\.map/,'critical release assets must install atomically');
assert.match(sw,/precache_failed:/,'failed critical assets must abort activation instead of producing a mixed shell');
assert.match(sw,/deleteStaleNuvastoCaches/,'activation must delete old Nuvasto generations');
assert.doesNotMatch(sw,/PREVIOUS_CACHE_VERSION|LEGACY_CACHE_VERSION|PREVIOUS_VERSION/,'historical cache generations must not remain available');
assert.match(sw,/client\.navigate\(client\.url\)/,'activated current worker must force open stale clients onto the current shell');
assert.match(sw,/safe-area-v95\.css/,'safe-area stylesheet remains part of the current shell');
assert.match(sw,/app-navigation\.js/,'current navigation must be available offline');
assert.match(sw,/app-suppliers\.js/,'current supplier workspace must be available offline');
assert.match(sw,/app-company-profile\.js/,'current company profile must be available offline');
assert.match(sw,/app-release-guard\.js/,'current release guard must be available offline');
assert.match(sw,/app-location-identity\.js/,'location profile module must be available offline');
assert.doesNotMatch(sw,/'\.\/app-procurement\.js'/,'noncritical procurement bundle must stay out of install precache');
assert.match(payments,/openPaymentDocumentComposer/,'payment document workflow must remain available');
assert.match(payments,/openCollectivePayment/,'collective payment workflow must remain available');
assert.doesNotMatch(payments,/MutationObserver/,'payment workflow must not observe the whole DOM');
console.log(`release contracts: OK · ${release.release} · generated handshake · latest-only cache`);
